# fhr.json's orcidUri pattern (a prefix match), and the ROR identifier form.
ORCID_URI = re.compile(r"https://orcid\.org/[0-9]{4}-[0-9]{4}-[0-9]{4}-[0-9]{3}[0-9X]")
ROR_URI = re.compile(r"https://ror\.org/0[0-9a-z]{6}[0-9]{2}")
