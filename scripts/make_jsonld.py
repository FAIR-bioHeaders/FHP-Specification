def collect_terms(model, root_class=ROOT_CLASS):
    """fhr-namespace classes and properties reachable from ``root_class``."""
    classes, properties = {}, {}
    for class_name, _, slots in model.walk(root_class):
        class_iri = model.class_iri(class_name)
        cls = model.view.get_class(class_name)
        extra = annotations(cls)
        if class_iri.startswith(FHR):
            name = class_iri[len(FHR):]
            classes[name] = {
                "comment": extra.get("vocabulary_comment") or cls.description,
                "subClassOf": [extra["vocabulary_subclass_of"]]
                if "vocabulary_subclass_of" in extra else [],
                "closeMatch": list(cls.close_mappings or []),
            }
        for slot in slots:
            iri = model.iri(slot)
            if annotations(slot).get("jsonld_node_id") is True or not iri.startswith(FHR):
                continue
            name = iri[len(FHR):]
            entry = properties.setdefault(name, {
                "comment": slot.description,
                "domain": [],
                "domain_classes": [],
                "range": [],
                "subPropertyOf": [m for m in slot.broad_mappings or [] if m.startswith("sdo:")],
            })
            domain = compact(class_iri)
            if domain not in entry["domain"]:
                entry["domain"].append(domain)
                entry["domain_classes"].append(class_name)
            ranges = [slot.range] + [option.range for option in slot.any_of or []]
            for kind in ranges:
                if not kind:
                    continue
                if model.view.get_class(kind) is not None:
                    for value in type_terms(model, kind).values():
                        if value not in entry["range"]:
                            entry["range"].append(value)
                    continue
                else:
                    base = kind
                    linkml_type = model.view.get_type(kind)
                    if model.view.get_enum(kind) is not None:
                        # An enum is a string value; the permissible values stay in
                        # the model, not the vocabulary (FHP sourceType, isoformPolicy,
                        # completeness.mode). FHR has no enum-valued slot.
                        base = "string"
                    elif kind not in RANGE_IRIS and linkml_type is not None:
                        base = {"str": "string"}.get(linkml_type.base, linkml_type.typeof)
                    value = RANGE_IRIS[base]
                if value not in entry["range"]:
                    entry["range"].append(value)
    for kind, terms in (("class", classes), ("property", properties)):
        for name, entry in terms.items():
            if not (entry["comment"] or "").strip():
                raise ValueError(f"{kind} fhr:{name} has no description (FR-002)")
    return classes, properties


def ordered(terms):
    return sorted(terms, key=lambda name: (name.casefold(), name))


def turtle_string(text):
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"@en'


