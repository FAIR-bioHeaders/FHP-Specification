ABSOLUTE_URL = re.compile(r"[A-Za-z][A-Za-z0-9+.-]*://\S+")
# assemblyProtocolHowTo is used only by the export profile (013 research R-06).
EXPORT_KEYS = ("id", "url", "keywords", "assemblyProtocolHowTo")
