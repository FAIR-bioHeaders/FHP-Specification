def _iris(curies):
    return [{"@id": curie} for curie in curies]


def _text(value):
    return {"@value": value, "@language": "en"}


# The ontology node of the FHR vocabulary as JSON-LD (the default of
# ``build_terms_jsonld``). The FHP additions supply their own label, comment and
# ``seeAlso`` without changing the FHR output.
FHR_ONTOLOGY = {
    "label": "FAIR-bioHeaders vocabulary",
    "comment": "Terms for FAIR-bioHeaders metadata that have no schema.org "
               "equivalent. Generated from the FAIR-bioHeaders-Specification LinkML "
               "model; do not edit.",
    "see_also": "https://github.com/FAIR-bioHeaders/FAIR-bioHeaders-Specification/blob/"
                "main/docs/TERMS.md",
}


def build_terms_jsonld(classes, properties, ontology=FHR_ONTOLOGY):
    """The vocabulary as JSON-LD, with the same triples as ``build_turtle``."""
    defined_by = {"@id": VOCABULARY}
    graph = [{
        "@id": VOCABULARY,
        "@type": "owl:Ontology",
        "rdfs:label": _text(ontology["label"]),
        "rdfs:comment": _text(ontology["comment"]),
        "dcterms:license": {"@id": "https://www.mozilla.org/en-US/MPL/2.0/"},
        "rdfs:seeAlso": {"@id": ontology["see_also"]},
    }]
    for name in ordered(classes):
        entry = classes[name]
        node = {"@id": f"fhr:{name}", "@type": "rdfs:Class",
                "rdfs:label": _text(name), "rdfs:comment": _text(entry["comment"])}
        if entry["subClassOf"]:
            node["rdfs:subClassOf"] = _iris(entry["subClassOf"])
        if entry["closeMatch"]:
            node["skos:closeMatch"] = _iris(entry["closeMatch"])
        node["rdfs:isDefinedBy"] = defined_by
        graph.append(node)
    for name in ordered(properties):
        entry = properties[name]
        node = {"@id": f"fhr:{name}", "@type": "rdf:Property",
                "rdfs:label": _text(name), "rdfs:comment": _text(entry["comment"]),
                "sdo:domainIncludes": _iris(entry["domain"]),
                "sdo:rangeIncludes": _iris(entry["range"])}
        if entry["subPropertyOf"]:
            node["rdfs:subPropertyOf"] = _iris(entry["subPropertyOf"])
        node["rdfs:isDefinedBy"] = defined_by
        graph.append(node)
    return json.dumps({"@context": JSONLD_PREFIXES, "@graph": graph}, indent=2) + "\n"


TERMS_INTRO = f"""# FAIR-bioHeaders vocabulary

<!-- Generated by scripts/make_jsonld.py from the LinkML model (schemas/core.yaml and
fhr_linkml.yml); do not edit. -->

This page defines the FAIR-bioHeaders terms that the [JSON-LD context](../jsonld/fhr.context.jsonld)
uses where schema.org has no suitable term. The namespace is `{FHR}`. It is unversioned: a term
IRI never changes and is never reused with another meaning. A deprecated term is kept and marked
deprecated.

- Machine-readable forms: [jsonld/terms.ttl](../jsonld/terms.ttl) (Turtle) and
  [jsonld/terms.jsonld](../jsonld/terms.jsonld) (JSON-LD).
- How records use the terms: [JSONLD.md](JSONLD.md) and the
  [mapping table](../mappings/fhr-jsonld-dcmi.yml).
- Licence: MPL-2.0. To cite a term, give its IRI and the FAIR-bioHeaders-Specification release.

Each heading is the term's local name, so `{FHR}checksum` is the section `#checksum` below.
"""


def curie_label(curie):
    return local_name(curie)


def build_terms_md(classes, properties, dcmi=None):
    parts = [TERMS_INTRO, "## Classes\n"]
    for name in ordered(classes):
        entry = classes[name]
        lines = [f"### {name}\n", f"`{FHR}{name}`. Class.\n", entry["comment"] + "\n"]
        bullets = []
        if entry["subClassOf"]:
            bullets.append("- Subclass of: " + ", ".join(f"`{c}`" for c in entry["subClassOf"]))
        if entry["closeMatch"]:
            bullets.append("- Close match: " + ", ".join(f"`{c}`" for c in entry["closeMatch"]))
        if bullets:
            lines.append("\n".join(bullets) + "\n")
        parts.append("\n".join(lines))
    parts.append("## Properties\n")
    for name in ordered(properties):
        entry = properties[name]
        used_on = ", ".join(
            f"{curie_label(domain)} ({DOMAIN_NOTES.get(cls, cls)})"
            for domain, cls in zip(entry["domain"], entry["domain_classes"])
        )
        bullets = [f"- Used on: {used_on}",
                   "- Value: " + ", ".join(curie_label(r) for r in entry["range"])]
        if entry["subPropertyOf"]:
            bullets.append("- Subproperty of: "
                           + ", ".join(f"`{p}`" for p in entry["subPropertyOf"]))
        if dcmi is not None:
            bullets.append(f"- DCMI: {dcmi[name]}")
        parts.append("\n".join([f"### {name}\n", f"`{FHR}{name}`. Property.\n",
                                entry["comment"] + "\n", "\n".join(bullets) + "\n"]))
    return "\n".join(parts)


