# FHP 1.0 / shared v0.4: a supplied DataCite nameType wins over the identifier.
NAME_TYPES = {"Personal": "Person", "Organizational": "Organization"}


def author_type(item):
    """data-model section 5: an explicit nameType wins; otherwise ORCID gives
    Person, ROR Organization, else Agent."""
    if item.get("nameType") in NAME_TYPES:
        return NAME_TYPES[item["nameType"]]
    uri = item.get("uri")
    if isinstance(uri, str) and ORCID_URI.match(uri):
        return "Person"
    if isinstance(uri, str) and ROR_URI.fullmatch(uri):
        return "Organization"
    return "Agent"


def is_absolute_url(value):
    return isinstance(value, str) and ABSOLUTE_URL.fullmatch(value) is not None


def check_export(export):
    """Validate an export context: optional id, url, keywords and assemblyProtocolHowTo
    (provisional)."""
    if not isinstance(export, dict):
        raise ValueError("export context must be a mapping with id, url and/or keywords")
    unknown = sorted(set(export) - set(EXPORT_KEYS))
    if unknown:
        raise ValueError(f"export context: unknown key {', '.join(map(str, unknown))}; "
                         "allowed: id, url, keywords, assemblyProtocolHowTo")
    if "assemblyProtocolHowTo" in export and not isinstance(export["assemblyProtocolHowTo"],
                                                             bool):
        raise ValueError("export context: assemblyProtocolHowTo must be true or false")
    for key in ("id", "url"):
        if key in export and not is_absolute_url(export[key]):
            raise ValueError(f"export context: {key} must be an absolute URL")
    keywords = export.get("keywords", ["x"])
    if not (isinstance(keywords, list) and keywords
            and all(isinstance(word, str) and word.strip() for word in keywords)):
        raise ValueError("export context: keywords must be a non-empty list of non-empty strings")
    return export


def _present(value):
    if isinstance(value, str):
        return bool(value.strip())
    if isinstance(value, list):
        return bool(value)
    return value is not None


def bioschemas_missing(document):
    """The Bioschemas Dataset minimum properties a written document lacks."""
    return [name for name, key in BIOSCHEMAS_MINIMUM if not _present(document.get(key))]


def _reserved_keys(value, path):
    if isinstance(value, dict):
        for key, item in value.items():
            here = f"{path}.{key}" if path else key
            if key.startswith("@"):
                raise ValueError(f"JSON-LD: {here} starts with @, which JSON-LD reserves; "
                                 "it cannot be written")
            _reserved_keys(item, here)
    elif isinstance(value, list):
        for index, item in enumerate(value):
            _reserved_keys(item, f"{path}[{index}]")


def _typed(key, value):
    if key in NODE_TYPES and isinstance(value, dict):
        return {"@type": NODE_TYPES[key], **copy.deepcopy(value)}
    if key in AUTHOR_KEYS and isinstance(value, list):
        return [{"@type": author_type(item), **copy.deepcopy(item)}
                if isinstance(item, dict) else copy.deepcopy(item) for item in value]
    if key == "assemblySoftware" and isinstance(value, list):
        return [{"@type": "SoftwareApplication", **copy.deepcopy(item)}
                if isinstance(item, dict) else copy.deepcopy(item) for item in value]
    return copy.deepcopy(value)


def to_jsonld(record, export=None, context=None):
    """The JSON-LD document for an FHR record (contracts/cli.md "Writing")."""
    _reserved_keys(record, "")
    for key in (URL_TERM, *EXPORT_OUTPUT):
        if key in record:
            raise ValueError(f"JSON-LD: the root key {key} is reserved for JSON-LD output")
    if export is not None:
        export = check_export(export)
    context = load_context() if context is None else context
    document = {"@context": context["@context"], "@type": "Dataset"}
    if export and "id" in export:
        document["@id"] = export["id"]
    for key, value in record.items():
        if key == "documentation" and is_absolute_url(value):
            document[URL_TERM] = value
        else:
            document[key] = _typed(key, value)
    if export:
        for key in ("keywords", "url"):
            if key in export:
                document[key] = copy.deepcopy(export[key])
        if not bioschemas_missing(document):
            document["conformsTo"] = BIOSCHEMAS_DATASET_PROFILE
    return document


def jsonld_text(record, export=None, context=None):
    return json.dumps(to_jsonld(record, export, context), ensure_ascii=False, indent=2) + "\n"


