def schemaorg_subset(source, context=None):
    """The schema.org terms the context uses, from a local copy of the release file."""
    import hashlib

    data = Path(source).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SCHEMAORG_SHA256:
        raise ValueError(f"{source}: SHA-256 {digest} is not the pinned schema.org file")
    graph = {node["@id"]: node for node in json.loads(data)["@graph"]}
    context = load_context() if context is None else context
    names = (set(re.findall(r'"sdo:([A-Za-z]+)"', json.dumps(context)))
             | set(SCHEMAORG_BASE_TERMS) | set(EXPORT_SCHEMAORG_TERMS))

    def ids(value):
        value = value if isinstance(value, list) else [] if value is None else [value]
        return sorted(item["@id"].split(":", 1)[1] for item in value
                      if item["@id"].startswith("schema:"))

    terms = {}
    for name in sorted(names):
        node = graph.get(f"schema:{name}")
        if node is None:
            raise ValueError(f"schema.org has no term {name}")
        kinds = node["@type"] if isinstance(node["@type"], list) else [node["@type"]]
        parts = node.get("schema:isPartOf")
        parts = parts if isinstance(parts, list) else [parts] if parts else []
        terms[name] = {
            "type": "Property" if "rdf:Property" in kinds else "Class",
            "domainIncludes": ids(node.get("schema:domainIncludes")),
            "rangeIncludes": ids(node.get("schema:rangeIncludes")),
            "subClassOf": ids(node.get("rdfs:subClassOf")),
            "pending": any(part["@id"] == "https://pending.schema.org" for part in parts),
        }
    return {"_source": SCHEMAORG_SOURCE, "_sha256": SCHEMAORG_SHA256,
            "_retrieved": "https://schema.org/version/latest/schemaorg-current-https.jsonld "
                          "(2026-10-10, release v30.1)",
            "terms": terms}


