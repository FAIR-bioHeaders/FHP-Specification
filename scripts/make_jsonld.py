# The mapping table summaries (US2).


def load_table():
    import yaml

    return yaml.safe_load(MAPPING_TABLE.read_text(encoding="utf-8"))


def short(iri):
    if iri in ("@id", "none"):
        return iri
    for prefix, namespace in (("schema", SDO), ("fhr", FHR), ("dcterms", DCT)):
        if iri.startswith(namespace):
            return f"{prefix}:{iri[len(namespace):]}"
    return iri


def mappings_summary(table):
    """The Markdown summary of the mapping table: one row per FHR path."""
    lines = ["| FHR path | JSON-LD term | JSON-LD kind | DCMI term | DCMI kind |",
             "| --- | --- | --- | --- | --- |"]
    for entry in table["entries"]:
        dcmi = entry["dcmi"]
        lines.append("| `{}` | `{}` | {} | {} | {} |".format(
            entry["path"], short(entry["jsonld"]["term"]), entry["jsonld"]["kind"],
            "; ".join(f"`{short(m['term'])}`" if m["term"] != "none" else "none" for m in dcmi),
            "; ".join(m["kind"] for m in dcmi)))
    return "\n".join(lines) + "\n"


def dcmi_lines(table):
    """The DCMI line of each fhr: property in docs/TERMS.md."""
    lines = {}
    for entry in table["entries"]:
        term = entry["jsonld"]["term"]
        if not term.startswith(FHR):
            continue
        texts = [f"`{short(m['term'])}` ({m['kind']})" for m in entry["dcmi"] if m["term"] != "none"]
        lines[term[len(FHR):]] = ("; ".join(texts) if texts else "none") + \
            " (see the [mapping table](../mappings/fhr-jsonld-dcmi.yml))"
    return lines


def mappings_doc(table):
    text = MAPPINGS_DOC.read_text(encoding="utf-8")
    start, end = text.find(SUMMARY_START), text.find(SUMMARY_END)
    if start < 0 or end < start:
        raise ValueError("docs/MAPPINGS.md has no generated summary markers")
    return text[:start] + SUMMARY_START + "\n\n" + mappings_summary(table) + "\n" + text[end:]


def fhp_outputs(fhr_terms=None, context=None):
    """The FHP context, vocabulary additions and example fixtures (issue #4)."""
    fhr_classes, fhr_properties = collect_terms(Model()) if fhr_terms is None else fhr_terms
    fhp_model = Model(FHP_LINKML, FHP_SCHEMA)
    context = (build_context(fhp_model, FHP_ROOT_CLASS, export_terms=False,
                             ordered_slots=FHP_ORDERED_SLOTS)
               if context is None else context)
    all_classes, all_properties, added_classes, added_properties = \
        fhp_term_additions(fhp_model, fhr_classes, fhr_properties)
    core, family, fhp_owned = fhp_term_origins()
    terms = set(all_classes) | set(all_properties)
    published = set(FHP_PUBLISHED_SHARED)
    groups = {
        "published": sorted(published & terms),
        "core": sorted((core & terms) - published),
        "family": sorted((family & terms) - published - core),
        "fhp": sorted((terms - set(fhr_classes) - set(fhr_properties) - published
                       - core - family)),
    }
    return {
        FHP_CONTEXT_PATH: json.dumps(context, indent=2) + "\n",
        FHP_TERMS_PATH: build_turtle(added_classes, added_properties,
                                     fhp_turtle_header(groups)),
        FHP_TERMS_JSONLD_PATH: build_terms_jsonld(added_classes, added_properties,
                                                  FHP_ONTOLOGY),
        **fhp_example_outputs(context),
    }


def generate():
    """Return ``{path: text}`` for every generated file."""
    model = Model()
    context = build_context(model)
    classes, properties = collect_terms(model)
    table = load_table()
    return {
        CONTEXT_PATH: json.dumps(context, indent=2) + "\n",
        TERMS_PATH: build_turtle(classes, properties),
        TERMS_JSONLD_PATH: build_terms_jsonld(classes, properties),
        TERMS_DOC: build_terms_md(classes, properties, dcmi_lines(table)),
        MAPPINGS_DOC: mappings_doc(table),
        **example_outputs(context),
        **export_outputs(),
        **fhp_outputs((classes, properties)),
    }


def check(outputs):
    stale = False
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            stale = True
            relative = path.relative_to(ROOT).as_posix()
            sys.stdout.writelines(difflib.unified_diff(
                current.splitlines(keepends=True), text.splitlines(keepends=True),
                f"a/{relative}", f"b/{relative} (generated)"))
    if stale:
        print("Generated JSON-LD files are out of date; run python scripts/make_jsonld.py",
              file=sys.stderr)
        return 1
    print("JSON-LD context, vocabulary and generated documents are up to date.")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 with a diff if a generated file is out of date")
    parser.add_argument("--examples", action="store_true",
                        help="write only the examples/*.fhr.jsonld and examples/fhp/*.fhp.jsonld "
                             "files from the committed contexts")
    parser.add_argument("--mappings-summary", action="store_true",
                        help="print the mapping table summary (Markdown) and exit")
    parser.add_argument("--schemaorg-subset", metavar="SOURCE",
                        help="write tests/fixtures/schemaorg-v30.1-subset.json from a local "
                             "copy of schemaorg-current-https.jsonld (manual download)")
    args = parser.parse_args(argv)
    if args.mappings_summary:
        sys.stdout.write(mappings_summary(load_table()))
        return 0
    try:
        if args.schemaorg_subset:
            subset = schemaorg_subset(args.schemaorg_subset)
            outputs = {SCHEMAORG_SUBSET: json.dumps(subset, indent=2) + "\n"}
        elif args.examples:
            outputs = {**example_outputs(load_context()), **export_outputs(),
                       **fhp_example_outputs()}
        else:
            outputs = generate()
    except ValueError as error:
        print(f"make_jsonld: {error}", file=sys.stderr)
        return 1
    if args.check:
        return check(outputs)
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
