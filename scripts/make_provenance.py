"""Generate SHA-256 provenance entries for the pinned shared-specification artifacts.

The entries describe the byte-for-byte copies of FAIR-bioHeaders-Specification
at the pinned v0.5.0 release commit that this development repository maintains
(issue #3, docs/DEVELOPMENT-TREE-PROPOSAL.md section 3). One subset — the FHP
contract chain (``fhp.json``, ``fhp_linkml.yml``, ``schemas/shared.yaml``,
``schemas/versions.json``) and the released-contract fixture
``tests/fixtures/releases/fhp-v0.6.0.json`` — is instead taken from the shared
v0.6.0 release commit (FHP-Specification#31: the tree must validate the FHP 1.2
contract it owns; every other copy stays at v0.5.0 until a full resync). Each
such entry records its per-entry ``commit``. Copies carry a
machine-checkable local adjustment instead of plain identity:

- ``fhp_linkml.yml`` retargets the model imports to the vendored snapshots
  (docs/DEVELOPMENT-TREE-PROPOSAL.md Q3, extended by #31), so the shared
  ``schemas/core`` and ``schemas/shared`` import lines are replaced by
  ``schemas/core-v0.5`` and ``schemas/shared-v0.6``;
- ``schemas/core-v0.5.yaml`` is the shared core payload behind a pinned
  provenance comment header, following this tree's ``schemas/core-v0.4.yaml``;
- ``schemas/shared-v0.6.yaml`` is the v0.6.0 shared object model behind its own
  provenance header, so the FHP 1.2 model reads it while the plain
  ``schemas/shared.yaml`` stays at v0.5.0 for the frozen FHGFF3 1.0 generation.

Adjusted entries record both digests (``sha256`` for the local bytes,
``upstreamSha256`` for the pinned upstream bytes) plus the ``adjustment``;
``scripts/check_shared_parity.py`` re-applies the transformation in both
directions. ``examples/fhp/rich-predicted.fhp.yaml`` is pinned to the companion
fix commit ``e1e5998`` (post-v0.5.0, shared issue #201) via a per-entry
``commit``. ``docs/FORMAT.md`` and every ``fhp-fasta`` vector the v0.5.0
manifest added or changed joined this set when the Q4 decision
(docs/DEVELOPMENT-TREE.md, FAIR-bioHeaders/FHP-Specification#2, 2026-11-12)
wired the FHP-owned conformance package; ``conformance/manifest.json`` itself
is generated by this tree (scripts/make_conformance.py), not copied. The
remaining family-doc and contract copies stay frozen under
``legacy``/``pinned`` in ``provenance.json``, per the Q2 freeze.
"""

