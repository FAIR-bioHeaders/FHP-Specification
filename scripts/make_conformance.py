        lines = with_metadata(k, insert=[(f"genome: {GENOME}", ["genome: Second genome value"])])
        data, _ = assemble(lines + body(k))
        invalid(f"{k}-duplicate-key", k, data, "R8", "The root key genome appears twice.")
